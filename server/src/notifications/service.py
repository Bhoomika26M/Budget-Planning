"""Notification & reminder system.

Notifications are stored per user. Automatic alerts (budget limits, goal
deadlines, savings reminders, monthly reports) are generated by
`generate_alerts`, which is cheap and idempotent thanks to the per-user
unique `key` column – calling it repeatedly never creates duplicates.
"""

from datetime import date, datetime, timedelta, timezone

from sqlalchemy import func
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from src.entities.user import User
from src.notifications.entity import Notification

TYPE_COLORS = {
    "alert": "#e53e3e",
    "reminder": "#2E93C7",
    "success": "#22c55e",
    "info": "#5FA7D2",
}


def create_notification(
    db: Session,
    user_id: int,
    type_: str,
    title: str,
    body: str,
    color: str | None = None,
    key: str | None = None,
):
    """Create a notification. With a `key`, it is created only once per user."""
    if key and db.query(Notification.id).filter(
        Notification.user_id == user_id, Notification.key == key
    ).first():
        return None

    notification = Notification(
        user_id=user_id,
        type=type_,
        title=title[:200],
        body=body[:500],
        color=color or TYPE_COLORS.get(type_, "#2E93C7"),
        key=key,
    )
    db.add(notification)
    try:
        db.commit()
    except IntegrityError:  # created concurrently by another request
        db.rollback()
        return None
    db.refresh(notification)
    return notification


def remove_by_key(db: Session, user_id: int, key: str):
    db.query(Notification).filter(
        Notification.user_id == user_id, Notification.key == key
    ).delete(synchronize_session=False)
    db.commit()


def list_notifications(db: Session, user_id: int):
    return (
        db.query(Notification)
        .filter(Notification.user_id == user_id)
        .order_by(Notification.created_at.desc(), Notification.id.desc())
        .all()
    )


def find_notification(db: Session, user_id: int, notification_id: int):
    return db.query(Notification).filter(
        Notification.id == notification_id, Notification.user_id == user_id
    ).first()


def mark_all_read(db: Session, user_id: int):
    db.query(Notification).filter(
        Notification.user_id == user_id, Notification.read.is_(False)
    ).update({"read": True}, synchronize_session=False)
    db.commit()


def unread_count(db: Session, user_id: int) -> int:
    return db.query(func.count(Notification.id)).filter(
        Notification.user_id == user_id, Notification.read.is_(False)
    ).scalar() or 0


# ── Automatic alerts ───────────────────────────────────────────────

def _budget_alerts(db: Session, user: User, today: date):
    # Imported here to avoid circular imports (budgets -> notifications).
    from src.budgets.service import budgets_with_spent

    month_key = today.strftime("%Y-%m")
    budgets = [b for b in budgets_with_spent(db, user.id) if b.period == "monthly"]

    for budget in budgets:
        if budget.amount <= 0:
            continue
        pct = budget.spent / budget.amount * 100
        near_key = f"budget-near-{budget.category.lower()}-{month_key}"
        over_key = f"budget-exceeded-{budget.category.lower()}-{month_key}"

        if pct >= 100:
            create_notification(
                db, user.id, "alert",
                f"🚨 Budget Exceeded — {budget.category}",
                f"You've spent ₹{budget.spent:,.0f} against a ₹{budget.amount:,.0f} budget for "
                f"{budget.category}. You're ₹{budget.spent - budget.amount:,.0f} over limit.",
                color="#e53e3e", key=over_key,
            )
        elif pct >= 90:
            create_notification(
                db, user.id, "alert",
                f"⚠️ Budget Almost Full — {budget.category}",
                f"You've used {pct:.0f}% of your {budget.category} budget. Only "
                f"₹{budget.amount - budget.spent:,.0f} remaining — spend carefully.",
                color="#f59e0b", key=near_key,
            )

    # Overall monthly limit
    if user.monthly_budget and user.monthly_budget > 0:
        from src.expenses.service import spent_by_category

        total = sum(spent_by_category(db, user.id, today.year, today.month).values())
        pct = total / user.monthly_budget * 100
        if pct >= 100:
            create_notification(
                db, user.id, "alert",
                "🚨 Monthly Budget Exceeded",
                f"You've spent ₹{total:,.0f} this month — over your ₹{user.monthly_budget:,.0f} monthly budget.",
                color="#e53e3e", key=f"monthly-exceeded-{month_key}",
            )
        elif pct >= 90:
            create_notification(
                db, user.id, "alert",
                "⚠️ Monthly Budget Almost Used",
                f"You've used {pct:.0f}% of your ₹{user.monthly_budget:,.0f} monthly budget.",
                color="#f59e0b", key=f"monthly-near-{month_key}",
            )


def _goal_alerts(db: Session, user: User, today: date):
    from src.savings.entity import SavingsContribution, SavingsGoal

    goals = db.query(SavingsGoal).filter(
        SavingsGoal.user_id == user.id, SavingsGoal.saved < SavingsGoal.target
    ).all()

    for goal in goals:
        if not goal.deadline:
            continue
        days_left = (goal.deadline - today).days
        if 0 <= days_left <= 30:
            urgency = "🚨" if days_left <= 3 else "⚠️" if days_left <= 7 else "📅"
            label = "today!" if days_left == 0 else "tomorrow!" if days_left == 1 else f"in {days_left} days"
            create_notification(
                db, user.id, "alert" if days_left <= 7 else "reminder",
                f"{urgency} Goal Due Soon — {goal.name}",
                f'Your "{goal.name}" goal deadline is {label}. '
                f"₹{goal.target - goal.saved:,.0f} still remaining.",
                color="#e53e3e" if days_left <= 3 else "#f59e0b" if days_left <= 7 else "#2E93C7",
                key=f"goal-due-{goal.id}-{goal.deadline.isoformat()}-{'soon' if days_left <= 7 else 'month'}",
            )

    # Weekly savings reminder when no contribution was made in the last 7 days
    if goals:
        last = db.query(func.max(SavingsContribution.date)).filter(
            SavingsContribution.user_id == user.id
        ).scalar()
        if last is None or (today - last).days >= 7:
            year, week, _ = today.isocalendar()
            goal = goals[0]
            create_notification(
                db, user.id, "reminder",
                "Savings Reminder",
                f"You haven't added to your {goal.name} fund this week. Small, regular savings add up!",
                color="#2E93C7", key=f"savings-reminder-{year}-{week}",
            )


def _monthly_report_alert(db: Session, user: User, today: date):
    from src.expenses.entity import Expense

    last_month_end = today.replace(day=1) - timedelta(days=1)
    has_data = db.query(Expense.id).filter(
        Expense.user_id == user.id,
        func.extract("year", Expense.expense_date) == last_month_end.year,
        func.extract("month", Expense.expense_date) == last_month_end.month,
    ).first()

    if has_data:
        label = last_month_end.strftime("%B %Y")
        create_notification(
            db, user.id, "info",
            "Monthly Report Ready",
            f"Your {label} financial report is ready to view and download.",
            color="#5FA7D2", key=f"report-{last_month_end.strftime('%Y-%m')}",
        )


def generate_alerts(db: Session, user: User):
    """Create any automatic notifications that are due for this user."""
    today = datetime.now(timezone.utc).date()
    try:
        if user.pref_alerts:
            if user.role in ("premium", "admin"):
                _budget_alerts(db, user, today)
            _goal_alerts(db, user, today)
        if user.pref_reports and user.role in ("premium", "admin"):
            _monthly_report_alert(db, user, today)
    except Exception:  # alerts must never break the main request
        db.rollback()
